#!/usr/bin/env python3
"""The /copy-for-ai/ copy (website #364), carried by program from Aria's comments, never retyped.

source/ holds the two comments as posted: 6703346378 (en, zh-Hant, Ray approved in 6703356047) and
6703372880 (the other six). data.py is generated from them:

    python3 -I -B scripts/copy364/ingest.py          # write data.py
    python3 -I -B scripts/copy364/ingest.py --check  # fail if data.py isn't what the sources give

The 【待 quella-364】 marker comes off here. If quella-364 refutes ⌃⌥⌘C, the source to change is the
step, with Aria's "沒過時的步驟 2".
"""
import pprint
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
SOURCES = {"6703346378-en-zh-hant.md": {"en": "en", "zh-Hant": "zh-hant"},
           "6703372880-six.md": {name: name for name in ("zh-hans", "ja", "ko", "de", "fr", "es")}}
MARKER = "【待 quella-364】"


def block(text: str, heading: str) -> str:
    """The ```md block under `## heading`. Its output sample is indented, so only a fence at column 0 ends it."""
    match = re.search(rf"^## {re.escape(heading)}\n+```md\n(.*?)^```$", text, re.S | re.M)
    if not match:
        raise SystemExit(f"no copy for {heading}")
    return match.group(1)


def cells(line: str) -> list:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def parse(md: str) -> dict:
    title = re.search(r"^Title: (.+)$", md, re.M).group(1)
    description = re.search(r"^Meta description: (.+)$", md, re.M).group(1)
    head, *sections = re.split(r"^## ", md, flags=re.M)
    lines = [line for line in head.splitlines() if line.strip()]
    h1 = next(i for i, line in enumerate(lines) if line.startswith("# "))
    sample = [line[4:] for line in lines if line.startswith("    ")]
    if len(sections) != 4 or len(sample) != 5:
        raise SystemExit(f"unexpected shape: {title}")
    how, compare, path, more = [section.strip().split("\n", 1) for section in sections]
    table = [cells(line) for line in compare[1].splitlines() if line.startswith("|") and "---" not in line]
    return {
        "title": title, "description": description, "h1": lines[h1][2:], "lede": lines[h1 + 1], "sample_label": lines[h1 + 2],
        "sample": sample, "how_h": how[0],
        "steps": [re.sub(r"^\d\. ", "", line).replace(MARKER, "") for line in how[1].strip().splitlines()],
        "compare_h": compare[0], "table": table, "path_h": path[0], "path": path[1].strip(), "next_h": more[0],
        "next": [re.fullmatch(r"- \[(.+)\]\((.+)\)", line).group(1) for line in more[1].strip().splitlines()],
    }


def build() -> dict:
    data = {}
    for name, locales in SOURCES.items():
        text = (HERE / "source" / name).read_text(encoding="utf-8")
        for heading, locale in locales.items():
            data[locale] = parse(block(text, heading))
    return data


def main() -> int:
    source = ('"""Generated by ingest.py from source/. Do not edit: change the source and regenerate."""\n\nDATA = '
              + pprint.pformat(build(), width=120, sort_dicts=False) + "\n")
    target = HERE / "data.py"
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != source:
            print("data.py doesn't match source/")
            return 1
        print("data.py matches source/")
        return 0
    target.write_text(source, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
